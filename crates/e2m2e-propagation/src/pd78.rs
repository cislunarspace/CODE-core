#[cfg(test)]
mod tests {
    use super::*;
    use crate::butcher::explicit_rk_step;

    #[test]
    fn row_lengths_are_lower_triangular() {
        for i in 0..PD78_TABLE.stages {
            assert_eq!(PD78_TABLE.a[i].len(), i, "row {i} should have length {i}");
        }
    }

    #[test]
    fn butcher_rows_sum_to_c_nodes() {
        for i in 1..PD78_TABLE.stages {
            let row_sum: f64 = PD78_TABLE.a[i].iter().sum();
            assert!(
                (row_sum - PD78_TABLE.c[i]).abs() < 1e-12,
                "row {i} sum {row_sum} != c {}",
                PD78_TABLE.c[i]
            );
        }
    }

    #[test]
    fn weights_sum_to_one() {
        let b_sum: f64 = PD78_TABLE.b.iter().sum();
        let b_star_sum: f64 = PD78_TABLE.b_star.iter().sum();
        assert!((b_sum - 1.0).abs() < 1e-12, "b sum {b_sum} != 1");
        assert!((b_star_sum - 1.0).abs() < 1e-12, "b* sum {b_star_sum} != 1");
    }

    #[test]
    fn harmonic_oscillator_small_step_error() {
        // y'' = -y as first-order system [y, v]: y' = v, v' = -y.
        let f = |_t: f64, state: &[f64]| -> Result<Vec<f64>, std::convert::Infallible> {
            Ok(vec![state[1], -state[0]])
        };

        let y0 = vec![1.0, 0.0];
        let h = 1e-4;

        let (y1, error) = explicit_rk_step(&PD78_TABLE, 0.0, &y0, h, f, None).unwrap();

        let y_exact = vec![h.cos(), -h.sin()];
        let num_err = y1
            .iter()
            .zip(y_exact.iter())
            .map(|(a, b)| (a - b).powi(2))
            .sum::<f64>()
            .sqrt();

        // 8th-order method: far more accurate than PD45 at the same step.
        assert!(num_err < 1e-12, "numerical error {num_err} too large");
        assert!(error < 1e-12, "local truncation estimate {error} too large");
    }
}
